"""
core/caption_generator.py
Generates real synced captions using faster-whisper from actual audio.
Falls back to script-based timing if audio transcription fails.
"""

from __future__ import annotations

import json
import re
from pathlib import Path


def _fmt_time(seconds: float) -> str:
    ms = int((seconds - int(seconds)) * 1000)
    s = int(seconds) % 60
    m = (int(seconds) // 60) % 60
    h = int(seconds) // 3600
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def generate_srt_from_audio(
    audio_path: Path,
    output_path: Path,
    model_size: str = "base",
) -> bool:
    """
    Generate SRT from actual audio using faster-whisper.
    Returns True if successful.
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        from faster_whisper import WhisperModel

        model = WhisperModel(model_size, device="cpu", compute_type="int8")
        segments, info = model.transcribe(
            str(audio_path),
            word_timestamps=True,
        )

        blocks = []
        idx = 1
        for segment in segments:
            start = segment.start
            end = segment.end
            text = segment.text.strip()
            if text:
                blocks.append(
                    f"{idx}\n{_fmt_time(start)} --> {_fmt_time(end)}\n{text}\n"
                )
                idx += 1

        if blocks:
            output_path.write_text("\n".join(blocks), encoding="utf-8")
            info_data = {
                "method": "faster-whisper",
                "model": model_size,
                "language": info.language,
                "segments": idx - 1,
            }
            info_path = output_path.parent / "caption_info.json"
            with open(info_path, "w", encoding="utf-8") as f:
                json.dump(info_data, f, indent=2)
            return True

        return False
    except Exception as e:
        error_path = output_path.parent / "caption_error.txt"
        error_path.write_text(f"faster-whisper failed: {e}\n", encoding="utf-8")
        return False


def generate_srt_from_script(
    script: str,
    duration: float,
    output_path: Path,
) -> None:
    """Fallback: generate SRT from script text with estimated timing."""
    lines = []
    for raw in script.splitlines():
        text = raw.strip()
        if not text:
            continue
        skip = ("title:", "topic:", "quiz:", "lesson:", "channel:")
        if any(text.lower().startswith(s) for s in skip):
            continue
        parts = re.split(r"(?<=[.!?])\s+", text)
        for part in parts:
            part = part.strip()
            if part:
                lines.append(part[:110])

    lines = lines or ["Video generated by the system."]
    per_line = max(1.5, duration / max(1, len(lines)))
    output_path.parent.mkdir(parents=True, exist_ok=True)

    blocks = []
    t = 0.0
    for i, line in enumerate(lines, start=1):
        start = t
        end = min(duration, t + per_line)
        blocks.append(f"{i}\n{_fmt_time(start)} --> {_fmt_time(end)}\n{line}\n")
        t = end

    output_path.write_text("\n".join(blocks), encoding="utf-8")

    info_path = output_path.parent / "caption_info.json"
    with open(info_path, "w", encoding="utf-8") as f:
        json.dump({"method": "script-fallback", "segments": len(lines)}, f, indent=2)


def generate_srt(
    script: str,
    duration: float,
    output_path: Path,
    audio_path: Path = None,
) -> None:
    """
    Main caption generator.
    Uses faster-whisper on actual audio for perfect sync.
    Falls back to script-based timing.
    """
    if audio_path and audio_path.exists() and audio_path.stat().st_size > 5000:
        success = generate_srt_from_audio(audio_path, output_path)
        if success:
            return

    generate_srt_from_script(script, duration, output_path)
